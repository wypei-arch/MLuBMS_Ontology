"""
Checks that bms:hasArchetype is inferred by OWL 2 RL from archetype class
membership, rather than only being written by Python (Reviewer 1, minor
comment 11).

The archetype definitions generated by ontology_reasoning.build_archetype_tbox
contain, for each archetype class A,
  * an owl:equivalentClass intersection of bms:Building and owl:hasValue
    restrictions on use type, construction-year bucket and structural
    category, so OWL 2 RL infers class membership; and
  * the axiom  A rdfs:subClassOf [ owl:onProperty bms:hasArchetype ;
    owl:hasValue A ],  so OWL 2 RL also infers the bms:hasArchetype link
    from that membership (rule cls-hv2).

This script:
  1. builds the live graph with these archetype definitions
     (ontology_reasoning.build_live_graph_with_dl_tbox);
  2. removes every asserted bms:hasArchetype triple (those come from
     building.archetype_id in the database);
  3. runs OWL 2 RL closure and compares the inferred bms:hasArchetype links
     with building.archetype_id in the database.

Read-only against the database; the ontology file is not modified.
"""
import sqlite3

import owlrl
from rdflib import OWL, RDFS

from ontology_reasoning import BMS, DB_PATH, build_live_graph_with_dl_tbox


def main():
    conn = sqlite3.connect(f"file:{DB_PATH}?mode=ro", uri=True)
    cur = conn.cursor()
    db = {bid: aid for bid, aid in cur.execute("SELECT building_id, archetype_id FROM building")}
    archetypes = [aid for (aid,) in cur.execute("SELECT archetype_id FROM archetype")]
    conn.close()

    g = build_live_graph_with_dl_tbox()
    with_axiom = sum(
        1 for aid in archetypes
        if any((r, OWL.onProperty, BMS.hasArchetype) in g
               for r in g.objects(BMS[f"Archetype_{aid}"], RDFS.subClassOf))
    )
    print(f"archetype classes carrying the hasArchetype hasValue axiom: {with_axiom} of {len(archetypes)}")

    asserted = list(g.triples((None, BMS.hasArchetype, None)))
    for t in asserted:
        g.remove(t)
    print(f"removed {len(asserted)} asserted bms:hasArchetype triples")

    owlrl.DeductiveClosure(owlrl.OWLRL_Semantics).expand(g)

    inferred = {}
    for b, a in g.subject_objects(BMS.hasArchetype):
        bid = int(str(b).rsplit("_", 1)[-1])
        inferred.setdefault(bid, set()).add(int(str(a).rsplit("_", 1)[-1]))

    with_db = {b for b, a in db.items() if a is not None}
    match = sum(1 for b in with_db if inferred.get(b) == {db[b]})
    extra = {b: inferred[b] for b in inferred if b not in with_db or inferred[b] != {db[b]}}
    missing = sorted(b for b in with_db if b not in inferred)

    print(f"buildings with archetype_id in database: {len(with_db)} of {len(db)}")
    print(f"inferred link identical to database:     {match}")
    print(f"missing inferred link:                   {missing}")
    print(f"extra or different inferred links:       {extra}")
    ok = with_axiom == len(archetypes) and match == len(with_db) and not extra
    print("RESULT:", "PASS" if ok else "FAIL")


if __name__ == "__main__":
    main()
